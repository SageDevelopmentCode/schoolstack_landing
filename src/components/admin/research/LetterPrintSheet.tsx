import { Eye, LayoutDashboard } from "lucide-react";
import GardenRoot from "@/components/garden/GardenRoot";
import { Arrow, Leaf, Tape } from "@/components/garden/ui";
import type { OutreachLetter } from "@/data/outreach/types";

/** Every printed string on the card, in one place. */
const LETTER_CARD_COPY = {
  scanMe: "scan me",
  insideLabel: "What's inside",
  inside: [
    {
      key: "demo",
      lead: "A demo of",
      rest: "your website, enrollment, tuition, mobile app and staff portal.",
      Icon: LayoutDashboard,
      tile: "bg-[var(--sf-mint)] text-[var(--sf-forest)]",
    },
    {
      key: "snapshot",
      lead: "A snapshot of",
      rest: "your enrollment today, the way a parent sees it.",
      Icon: Eye,
      tile: "bg-[var(--sf-peach)] text-[var(--sf-clay-deep)]",
    },
  ],
  noLogin: "No login, nothing to sign up for.",
  signOff: "Julius · Sage Field, Round Rock · MudKitchen",
} as const;

/** One A2 insert card (4.25 × 5.5 in): the QR, the typed short link and what it opens. */
export function LetterQrCard({
  letter,
  schoolShortName,
  qrSvg,
  shortUrlLabel,
  exportTarget = false,
}: {
  letter: OutreachLetter;
  schoolShortName: string;
  qrSvg: string;
  shortUrlLabel: string;
  /** The card DownloadCardImageButton saves as a PNG. */
  exportTarget?: boolean;
}) {
  const greeting = `for ${letter.founder.firstName} at ${schoolShortName}`;
  return (
    <div
      {...(exportTarget ? { "data-letter-card-export": "" } : {})}
      className="letter-card sf-grid relative flex h-[5.5in] w-[4.25in] flex-col items-center overflow-hidden border border-dashed border-[var(--sf-ink)]/30 bg-[var(--sf-cream)] px-[0.38in] pb-[0.24in] pt-[0.3in] text-[var(--sf-ink)]">
      <p className={`sf-hand m-0 text-balance text-center leading-[1.02] text-[var(--sf-forest)] ${greeting.length > 36 ? "text-[24px]" : "text-[28px]"}`}>
        {greeting}
      </p>

      <div className="relative mt-[0.16in] flex flex-col items-center">
        <div className="relative rounded-[22px] border-2 border-[var(--sf-ink)] bg-white p-[0.14in] shadow-[0_5px_0_0_var(--sf-ink)]">
          <Tape color="var(--sf-butter)" className="-top-3 left-1/2 -translate-x-1/2 -rotate-3" />
          {/* Generated by the qrcode package from our own short link, not user input. */}
          <div className="h-[1.5in] w-[1.5in] [&>svg]:h-full [&>svg]:w-full" dangerouslySetInnerHTML={{ __html: qrSvg }} />
          {/* Doodles hang off the QR box (not the column, which a long short link widens). */}
          <div aria-hidden="true" className="absolute -left-[0.95in] top-[0.14in] flex flex-col items-end">
            <span className="sf-hand -rotate-6 text-[19px] leading-none text-[var(--sf-clay-deep)]">{LETTER_CARD_COPY.scanMe}</span>
            <Arrow className="mr-1 mt-0.5 h-8 w-12 -scale-y-100 rotate-[-8deg]" color="var(--sf-clay-deep)" />
          </div>
          <Leaf className="absolute -right-[0.62in] bottom-[0.2in] h-8 w-8 rotate-12 opacity-80" color="var(--sf-moss)" />
        </div>
        <p className="m-0 mt-[0.13in] rounded-full bg-[var(--sf-butter)] px-3 py-1 text-[12.5px] font-extrabold tracking-tight text-[var(--sf-ink)]">
          {shortUrlLabel}
        </p>
      </div>

      <div className="mt-auto w-full">
        <p className="m-0 mb-2 text-[10px] font-extrabold uppercase tracking-[0.2em] text-[var(--sf-soft)]">
          {LETTER_CARD_COPY.insideLabel}
        </p>
        <ul className="m-0 list-none space-y-1.5 p-0">
          {LETTER_CARD_COPY.inside.map(({ key, lead, rest, Icon, tile }) => (
            <li key={key} className="flex items-start gap-2.5 rounded-2xl border-2 border-[var(--sf-ink)] bg-white px-2.5 py-1.5 shadow-[0_3px_0_0_var(--sf-ink)]">
              <span className={`flex h-7 w-7 shrink-0 items-center justify-center rounded-lg ring-2 ring-[var(--sf-ink)] ${tile}`}>
                <Icon className="h-4 w-4" strokeWidth={2.4} aria-hidden="true" />
              </span>
              <span className="text-[12px] leading-snug">
                <strong className="font-extrabold">{lead}</strong> {rest}
              </span>
            </li>
          ))}
        </ul>
        <p className="m-0 mt-2 text-center text-[11px] font-semibold text-[var(--sf-soft)]">{LETTER_CARD_COPY.noLogin}</p>
        <p className="m-0 mt-2 border-t border-dashed border-[var(--sf-ink)]/20 pt-2 text-center text-[9.5px] font-extrabold uppercase tracking-[0.16em] text-[var(--sf-soft)]">
          {LETTER_CARD_COPY.signOff}
        </p>
      </div>
    </div>
  );
}

/**
 * The printable sheet: two identical insert cards side by side on US Letter, with print CSS that hides
 * the admin chrome. Cut along the dashed lines. Wrapped in GardenRoot so the Garden fonts and tokens apply
 * (and the admin shell's `p` font rule doesn't override the handwriting).
 */
export function LetterPrintSheet(props: {
  letter: OutreachLetter;
  schoolShortName: string;
  qrSvg: string;
  shortUrlLabel: string;
}) {
  return (
    <GardenRoot className="letter-print-area flex justify-center gap-0 !bg-transparent">
      <div className="contents" data-testid="letter-print-sheet">
        <style>{`
          .letter-print-area { -webkit-print-color-adjust: exact; print-color-adjust: exact; }
          @media print {
            @page { size: letter portrait; margin: 0; }
            body * { visibility: hidden !important; }
            .letter-print-area, .letter-print-area * { visibility: visible !important; }
            .letter-print-area { position: fixed; left: 0; top: 0; width: 8.5in; padding: 0; margin: 0; }
          }
        `}</style>
        <LetterQrCard {...props} exportTarget />
        <LetterQrCard {...props} />
      </div>
    </GardenRoot>
  );
}

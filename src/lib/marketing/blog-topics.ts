import type { FeatureSlug } from "@/lib/marketing/features/types";
import type { BlogDemoId, BlogShotSrc, BlogToolId } from "@/lib/marketing/blog-demos";

/**
 * Researched blog topics for the website blog: what is happening for microschools, small private schools and
 * co-ops right now, what founders struggle with, and the feature-led and comparison posts that funnel to signup.
 * Shown in /admin/marketing/blog-topics. A topic's status comes from `website_blog_posts`: a post whose slug is
 * the topic's `targetSlug` makes it Draft or Published. Nothing else is stored.
 *
 * Search volumes are estimates (no keyword tool was used); confirm in Search Console or Ahrefs before writing.
 */

export type BlogTopicCluster = "timely" | "seasonal" | "founder" | "feature" | "comparison";
export type BlogTopicFunnel = "top" | "middle" | "bottom";
export type BlogTopicIntent = "informational" | "commercial";
export type BlogTopicPriority = 1 | 2 | 3;
export type BlogTopicVolume = "high" | "medium" | "low";

export type BlogTopicSource = { label: string; url: string };

/**
 * What the post shows inline, in order of use. `demo` = a live product demo (`<BlogDemo id>`),
 * `shot` = real screenshots (`<BlogShot src>`), `tool` = a free-tool card (`<BlogToolCallout tool>`),
 * `capture-needed` = nothing exists yet to show this, so capture it before writing.
 */
export type BlogTopicEmbed =
  | { kind: "demo"; id: BlogDemoId; caption: string }
  | { kind: "shot"; src: BlogShotSrc | BlogShotSrc[]; caption: string }
  | { kind: "tool"; tool: BlogToolId }
  | { kind: "capture-needed"; note: string };

const demo = (id: BlogDemoId, caption: string): BlogTopicEmbed => ({ kind: "demo", id, caption });
const shot = (src: BlogShotSrc | BlogShotSrc[], caption: string): BlogTopicEmbed => ({ kind: "shot", src, caption });
const tool = (id: BlogToolId): BlogTopicEmbed => ({ kind: "tool", tool: id });
const captureNeeded = (note: string): BlogTopicEmbed => ({ kind: "capture-needed", note });

export type BlogTopic = {
  id: string;
  /** The slug the post will use; matched against website_blog_posts for status. */
  targetSlug: string;
  /** Planned publish date (ISO). Posts go out Tuesdays and Thursdays from BLOG_SCHEDULE_START. */
  scheduledFor: string;
  workingTitle: string;
  primaryKeyword: string;
  secondaryKeywords: string[];
  intent: BlogTopicIntent;
  funnel: BlogTopicFunnel;
  cluster: BlogTopicCluster;
  /** Who it is for, in a few words. */
  audience: string;
  /** What the post argues or teaches, and how it leads to MudKitchen. */
  angle: string;
  /** Why this is worth writing now (news, season, search demand, founder pain). */
  whyNow: string;
  /** ISO date to publish by, for timely and seasonal topics. */
  publishBy?: string;
  featureSlugs: FeatureSlug[];
  cta: { label: string; href: string };
  /** Demos, screenshots and tools to put inside the post. */
  embeds: BlogTopicEmbed[];
  priority: BlogTopicPriority;
  volume: BlogTopicVolume;
  /** Notes for the writer: claims to avoid, facts to check. */
  caution?: string;
  sources: BlogTopicSource[];
};


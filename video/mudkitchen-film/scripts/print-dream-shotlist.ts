// Writes DREAM_SHOTLIST.md from src/dream/shots.ts and src/dream/edl.ts, so the
// shot list always matches the edit. Usage: npm run shotlist:dream
import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { BPM, DREAM_FPS, layout, type CutId } from "../src/dream/edl.ts";
import { SHOTS } from "../src/dream/shots.ts";

const here = dirname(fileURLToPath(import.meta.url));
const doc = resolve(here, "../DREAM_SHOTLIST.md");
const footage = resolve(here, "../public/footage/dream");

const tc = (frame: number) => `${(frame / DREAM_FPS).toFixed(1)}s`;
const esc = (s: string) => s.replace(/\|/g, "\\|");
const SOURCE = { stock: "Stock", ai: "AI", "stock-or-ai": "Stock, else AI" } as const;

const cutTable = (cut: CutId) => {
  const tl = layout(cut);
  const rows = tl.items.map((it) => {
    const time = `${tc(it.from)}–${tc(it.to)}`;
    if (it.kind === "shot") {
      const words = tl.words.filter((w) => w.shotIndex === it.index).map((w) => w.text).join(" ");
      const text = it.tag ? `\`\\ ${it.tag} \\\`` : words ? `“${esc(words)}”` : "";
      return `| ${time} | \`${it.shot}\` | ${text} |`;
    }
    if (it.kind === "flash") return `| ${time} | flash | app screen \`${it.image.split("/").pop()}\` |`;
    if (it.kind === "end") return `| ${time} | end card (${it.variant}) | “Built for Sage Field → your school.” → logo, “Run the school you imagined.”, CTA |`;
    return `| ${time} | black | (silence) |`;
  });
  return [`### ${cut}s cut (${tc(tl.duration)}, ${BPM} BPM)`, "", "| Time | Shot | On screen |", "|---|---|---|", ...rows].join("\n");
};

const shotRows = SHOTS.map((s) => {
  const have = existsSync(resolve(footage, `${s.id}.mp4`)) ? "✅" : "⬜";
  const search = s.search.map((q) => `“${esc(q)}”`).join("<br>");
  const speed = s.rate && s.rate < 1 ? `<br>**Slow motion (${s.rate}x): get a 50/60fps clip.**` : "";
  return `| ${have} | \`${s.id}\` | ${s.act} | ${esc(s.what)}${speed} | ${SOURCE[s.source]} | ${search} |`;
});

const prompts = SHOTS.filter((s) => s.ai).map((s) => `**\`${s.id}\`**\n\n> ${s.ai}\n`);

const out = `# Dream ad: shot list

Generated by \`npm run shotlist:dream\` from \`src/dream/shots.ts\` and \`src/dream/edl.ts\`. Edit those, not this file.

## How to add footage

1. Find each shot below (stock first, AI only where stock has nothing good). Any aspect ratio works; vertical or 4K landscape is best.
2. Save it as \`footage-source/dream/<shot id>.<ext>\` (e.g. \`footage-source/dream/d-mud-kitchen.mov\`).
3. Run \`npm run conform:dream\`. Studio and renders pick the clip up; missing ones stay as slates.
4. To use a later part of a clip, set \`srcIn\` (seconds) on that shot in \`src/dream/edl.ts\`. To reframe, change \`focus\` in \`src/dream/shots.ts\`.

**Licenses:** use a plan that covers paid social ads (Artlist / Storyblocks / Epidemic paid tiers; Pexels and Mixkit allow commercial use). Keep the license page or receipt for every clip. Check Meta / TikTok rules on labelling realistic AI-generated footage before running ads.

**Look:** don't grade clips beforehand. The edit applies one grade, grain, vignette and gate weave to all of them.

## Edit order

${cutTable("40")}

${cutTable("15")}

## Shots (${SHOTS.length})

| Have | Shot | Act | What it must show | Source | Search terms |
|---|---|---|---|---|---|
${shotRows.join("\n")}

## AI prompts (Veo / Kling / Runway)

Avoid close-ups of AI faces and any AI-made text or screens. Generate at 9:16 if the tool allows, 5–8s, then pick the best 1–2s.

${prompts.join("\n")}`;

writeFileSync(doc, out);
console.log(`[shotlist:dream] wrote ${doc}`);

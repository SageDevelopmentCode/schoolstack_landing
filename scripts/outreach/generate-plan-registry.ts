/**
 * Rewrites src/data/outreach/index.ts from the plan files in that folder.
 *
 * Usage:
 *   npx tsx --tsconfig tsconfig.json scripts/outreach/generate-plan-registry.ts [--check]
 *
 * A plan file is any `src/data/outreach/<slug>.ts` that exports `const <name>: OutreachPlan`.
 * Idempotent: the output depends only on which plan files exist, so several sessions writing plans at
 * once can each run it without dropping another session's plan. `--check` exits 1 if index.ts is stale.
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const DIR = resolve(process.cwd(), "src/data/outreach");
const INDEX = join(DIR, "index.ts");
const NOT_PLANS = new Set(["index.ts", "types.ts", "mudkitchen-capabilities.ts"]);

type Entry = { file: string; exportName: string };

function findPlans(): Entry[] {
  const entries: Entry[] = [];
  for (const file of readdirSync(DIR).sort()) {
    if (!file.endsWith(".ts") || file.endsWith(".test.ts") || NOT_PLANS.has(file)) continue;
    const source = readFileSync(join(DIR, file), "utf8");
    const match = source.match(/export const (\w+)\s*:\s*OutreachPlan\b/);
    if (!match) {
      console.warn(`skipping ${file}: no "export const <name>: OutreachPlan"`);
      continue;
    }
    entries.push({ file: file.replace(/\.ts$/, ""), exportName: match[1] });
  }
  return entries;
}

function render(entries: Entry[]): string {
  const imports = [
    ...entries.map((e) => ({ from: `./${e.file}`, line: `import { ${e.exportName} } from "./${e.file}";` })),
    { from: "./types", line: `import type { OutreachPlan } from "./types";` },
  ]
    .sort((a, b) => a.from.localeCompare(b.from))
    .map((i) => i.line);

  return `// Generated by scripts/outreach/generate-plan-registry.ts. Don't edit by hand: add a plan file and re-run it.
${imports.join("\n")}

export type * from "./types";
export { OUTREACH_FILL_IN_TOKENS } from "./types";

/** Researched outreach plans keyed by demo slug. */
export const outreachPlanRegistry: Record<string, OutreachPlan> = {
${entries.map((e) => `  [${e.exportName}.slug]: ${e.exportName},`).join("\n")}
};

export function getOutreachPlan(slug: string): OutreachPlan | null {
  return Object.prototype.hasOwnProperty.call(outreachPlanRegistry, slug) ? outreachPlanRegistry[slug] : null;
}

export function listOutreachPlans(): OutreachPlan[] {
  return Object.values(outreachPlanRegistry);
}
`;
}

const next = render(findPlans());
const current = readFileSync(INDEX, "utf8");
if (process.argv.includes("--check")) {
  if (current !== next) {
    console.error("src/data/outreach/index.ts is out of date. Run scripts/outreach/generate-plan-registry.ts.");
    process.exit(1);
  }
  console.log("Registry is up to date.");
} else if (current === next) {
  console.log("Registry already up to date.");
} else {
  writeFileSync(INDEX, next);
  console.log(`Wrote src/data/outreach/index.ts with ${findPlans().length} plan(s).`);
}
